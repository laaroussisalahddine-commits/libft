#include "libft.h"

t_list	*ft_lstlast(t_list *lst)
{
	t_list	*current;

	if (!lst)
		return (NULL);
	while (lst != NULL)
	{
		current = lst;
		lst = lst -> next;
	}
	return (current);
}
